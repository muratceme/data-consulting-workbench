def ws_connect(url, headers):
    return WebSocket(url, headers)


def jupyter_profile(cfg, factory, out):
    server = required(cfg, 'server')
    if not server.startswith('https://'):
        raise NativeError('server https:// ile başlamalı.')
    headers = {'Authorization': 'token ' + secret('JUPYTER_TOKEN')}
    client = factory(server, headers)
    data_path = required(cfg, 'data_path')
    if '\n' in data_path or len(data_path) > 500:
        raise NativeError('data_path tek satırlık sunucu yolu olmalı.')
    kernel = native.json_object(client.request('POST', 'api/kernels', {'name': cfg.get('kernel', 'python3')})[0]).get('id')
    if not kernel:
        raise NativeError('Kernel başlatılamadı.')
    journal(out, kernel_id=kernel)
    ws = None
    try:
        ws = ws_connect('wss://' + server.split('://', 1)[1].rstrip('/') + f'/api/kernels/{kernel}/channels', headers)
        msg_id, session = uuid.uuid4().hex, uuid.uuid4().hex
        ws.send(json.dumps({'header': {'msg_id': msg_id, 'username': 'datawork', 'session': session, 'msg_type': 'execute_request', 'version': '5.3',
                                       'date': dt.datetime.now(dt.timezone.utc).isoformat()}, 'parent_header': {}, 'metadata': {}, 'channel': 'shell',
                            'content': {'code': PROFILE_CODE.format(path=data_path), 'silent': False, 'store_history': False, 'user_expressions': {}, 'allow_stdin': False,
                                        'stop_on_error': True}}))
        output, error = '', None
        for _ in range(5000):
            msg = json.loads(ws.recv())
            if (msg.get('parent_header') or {}).get('msg_id') != msg_id:
                continue
            kind = (msg.get('header') or {}).get('msg_type') or msg.get('msg_type')
            content = msg.get('content') or {}
            if kind == 'stream' and content.get('name') == 'stdout':
                output += content.get('text', '')
            elif kind == 'error':
                error = f"{content.get('ename')}: {content.get('evalue')}"[:300]
            elif kind == 'status' and content.get('execution_state') == 'idle':
                break
    finally:
        if ws:
            ws.close()
        try:
            client.request('DELETE', f'api/kernels/{kernel}')
        except NativeError:
            journal(out, kernel_shutdown='failed')
    if error:
        raise NativeError('Kernel profil kodunda hata verdi: ' + error)
    marker = output.rfind('DATAWORK_PROFILE')
    if marker < 0:
        raise NativeError('Kernel profil çıktısı üretmedi.')
    result = json.loads(output[marker + len('DATAWORK_PROFILE'):].strip().splitlines()[0])
    return result['kolonlar'], {'satir': result['satir'], 'tekrarli_satir': result['tekrarli_satir'], 'calistirma': 'Jupyter kernel'}, []


