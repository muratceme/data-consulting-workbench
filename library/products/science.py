def records(frame):
    return [{k: plain(v) for k, v in r.items()} for r in frame.to_dict('records')]


# ---------- pandas ----------
def read_frame(pd, path):
    suffix = Path(path).suffix.lower()
    if suffix in ('.xlsx', '.xls'):
        return pd.read_excel(path)
    if suffix == '.parquet':
        return pd.read_parquet(path)
    return pd.read_csv(path, sep=None, engine='python')


def pandas_profile(cfg, factory, out):
    pd = driver('pandas')
    path = required(cfg, 'input_file')
    df = read_frame(pd, path)
    rows = []
    for col in df.columns:
        s = df[col]
        item = {'kolon': str(col), 'tip': str(s.dtype), 'satir': int(len(s)), 'dolu': int(s.notna().sum()), 'bos': int(s.isna().sum()),
                'bos_orani': round(float(s.isna().mean()), 4) if len(s) else 0, 'farkli': int(s.nunique(dropna=True))}
        if pd.api.types.is_numeric_dtype(s) and s.notna().any():
            item.update(min=plain(s.min()), max=plain(s.max()), ortalama=round(float(s.mean()), 6), std=round(float(s.std()), 6) if s.count() > 1 else 0,
                        carpiklik=round(float(s.skew()), 4) if s.count() > 2 else '', basiklik=round(float(s.kurt()), 4) if s.count() > 3 else '')
            q1, q3 = s.quantile(0.25), s.quantile(0.75)
            item['aykiri'] = int(((s < q1 - 1.5 * (q3 - q1)) | (s > q3 + 1.5 * (q3 - q1))).sum())
        rows.append(item)
    numeric = df.select_dtypes('number')
    corr = numeric.corr().round(4).reset_index().rename(columns={'index': 'kolon'}) if numeric.shape[1] > 1 else None
    extra = {'satir': int(len(df)), 'tekrarli_satir': int(df.duplicated().sum()), 'bellek_bayt': int(df.memory_usage(deep=True).sum())}
    return rows, extra, (records(corr) if corr is not None else [])


# ---------- SciPy ----------
def scipy_profile(cfg, factory, out):
    stats = driver('scipy.stats')
    columns, data = read_table(required(cfg, 'input_file'))
    rows = profile(columns, data)
    for item in rows:
        values = [number(r.get(item['kolon'])) for r in data]
        values = [v for v in values if v is not None]
        if item['tip'] in ('tamsayı', 'ondalık') and len(values) >= 8:
            item['carpiklik'] = round(float(stats.skew(values)), 4)
            item['basiklik'] = round(float(stats.kurtosis(values)), 4)
            test = stats.normaltest(values) if len(values) >= 20 else stats.shapiro(values)
            item['normallik_p'] = round(float(test.pvalue), 6)
            q1, q3 = sorted(values)[len(values) // 4], sorted(values)[3 * len(values) // 4]
            item['aykiri'] = sum(1 for v in values if v < q1 - 1.5 * (q3 - q1) or v > q3 + 1.5 * (q3 - q1))
    return rows, {'satir': len(data), 'test': 'normaltest (n≥20) / shapiro'}, []


