def run_tool(command, label, timeout):
    try:
        done = subprocess.run(command, capture_output=True, text=True, timeout=timeout, encoding='utf-8', errors='replace')
    except FileNotFoundError:
        raise NativeError(f'{label} bulunamadı; kurulu ve yolu doğru olmalı.') from None
    except subprocess.TimeoutExpired:
        raise NativeError(f'{label} zaman aşımına uğradı.') from None
    if done.returncode != 0:
        raise NativeError(f'{label} hata koduyla bitti ({done.returncode}): ' + (done.stderr or done.stdout)[-300:])
    return done


