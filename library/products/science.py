def cas_table(result, key):
    t = (result.get('results') or {}).get(key) or {}
    cols = [c.get('name') for c in t.get('schema', [])]
    return [dict(zip(cols, r)) for r in t.get('rows', [])]


def sas_profile(cfg, factory, out):
    client = factory(required(cfg, 'server'), {'Authorization': 'Bearer ' + secret('SAS_ACCESS_TOKEN')})
    base = cfg.get('cas_path', '/cas-shared-default-http/cas')
    if not re.fullmatch(r'/[A-Za-z0-9_/-]{1,100}', base):
        raise NativeError('cas_path geçersiz.')
    session = native.json_object(client.request('POST', base + '/sessions', {})[0]).get('session')
    if not session:
        raise NativeError('CAS oturumu açılamadı.')
    journal(out, cas_session=session)
    table = {'caslib': name(cfg, 'caslib'), 'name': name(cfg, 'table')}
    try:
        summary = client.json('POST', f'{base}/sessions/{ident(session)}/actions/simple.summary', {'table': table})
        distinct = client.json('POST', f'{base}/sessions/{ident(session)}/actions/simple.distinct', {'table': table})
    finally:
        try:
            client.request('DELETE', f'{base}/sessions/{ident(session)}')
        except NativeError:
            journal(out, cas_session_end='failed')
    dist = {str(r.get('Column')): r for r in cas_table(distinct, 'Distinct')}
    rows = []
    for r in cas_table(summary, 'Summary'):
        d = dist.get(str(r.get('Column')), {})
        rows.append({'kolon': r.get('Column'), 'tip': 'sayısal', 'satir': (number(r.get('N')) or 0) + (number(r.get('NMiss')) or 0), 'dolu': r.get('N'), 'bos': r.get('NMiss'),
                     'farkli': d.get('NDistinct'), 'min': r.get('Min'), 'max': r.get('Max'), 'ortalama': r.get('Mean'), 'std': r.get('Std'),
                     'carpiklik': r.get('Skewness'), 'basiklik': r.get('Kurtosis')})
    for col, d in dist.items():
        if col not in {str(r['kolon']) for r in rows}:
            rows.append({'kolon': col, 'tip': 'karakter', 'farkli': d.get('NDistinct'), 'bos': d.get('NMiss')})
    return rows, {'tablo': f"{table['caslib']}.{table['name']}", 'calistirma': 'CAS simple.summary + simple.distinct'}, []


# ---------- IBM SPSS Statistics (.sav) ----------
def spss_profile(cfg, factory, out):
    pyreadstat = driver('pyreadstat')
    df, meta = pyreadstat.read_sav(required(cfg, 'input_file'), apply_value_formats=False)
    data = records(df)
    rows = profile(list(df.columns), data)
    labels = dict(zip(meta.column_names, meta.column_labels or []))
    for item in rows:
        item['etiket'] = labels.get(item['kolon']) or ''
        item['olcek'] = (meta.variable_measure or {}).get(item['kolon'], '')
        vl = (meta.variable_value_labels or {}).get(item['kolon'])
        if vl:
            item['deger_etiketleri'] = len(vl)
    return rows, {'satir': len(data), 'dosya_etiketi': getattr(meta, 'file_label', '') or '', 'kodlama': getattr(meta, 'file_encoding', '')}, []


