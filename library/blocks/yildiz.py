"""Boyutsal model blokları: düz (denormalize) bir dosyayı yıldız şemaya çevirir. Boyut tabloları (vekil anahtar + “bilinmiyor” satırı),
tarih boyutu ve olgu tablosu için DDL ve yükleme SQL’i dört lehçede üretilir; üretilen SQLite SQL’i blok içinde gerçekten çalıştırılır ve
olgu tablosunun satır sayısı, ölçü toplamları ve anahtar eşleşmeleri kaynakla karşılaştırılır. Ambara bağlanmaz."""
import sqlite3
from collections import defaultdict
from datetime import date, timedelta
import tabular
from sqlgen import infer_column, snake
from islem import op, arg, Result, need, numbers

REQUIRES = ['sema_farki', 'sqlgen']
DIALECTS = ('sqlite', 'postgres', 'sqlserver', 'snowflake')
AY = ['Ocak', 'Şubat', 'Mart', 'Nisan', 'Mayıs', 'Haziran', 'Temmuz', 'Ağustos', 'Eylül', 'Ekim', 'Kasım', 'Aralık']
GUN = ['Pazartesi', 'Salı', 'Çarşamba', 'Perşembe', 'Cuma', 'Cumartesi', 'Pazar']


def parse_dims(spec, columns):
    """'urun=urun,kategori;bolge=bolge' -> {'urun': ['urun', 'kategori'], 'bolge': ['bolge']}"""
    dims = {}
    for part in [p for p in spec.split(';') if p.strip()]:
        if '=' not in part:
            raise ValueError(f'--dims biçimi “ad=sütun1,sütun2;ad2=sütun3” olmalı: {part}')
        name, cols = part.split('=', 1)
        cols = [c.strip() for c in cols.split(',') if c.strip()]
        missing = [c for c in cols if c not in columns]
        if missing or not cols:
            raise ValueError(f'{name}: dosyada olmayan sütun {", ".join(missing) or "(boş)"}. Sütunlar: {", ".join(columns)}')
        dims[snake(name.strip())] = cols
    used = [c for cols in dims.values() for c in cols]
    if len(used) != len(set(used)):
        raise ValueError('Bir sütun iki boyutta kullanılamaz.')
    return dims


SQL_TYPE = {'sqlite': {'int': 'INTEGER', 'bigint': 'INTEGER', 'decimal': 'NUMERIC', 'date': 'DATE', 'datetime': 'TEXT', 'bool': 'INTEGER', 'text': 'TEXT'},
            'postgres': {'int': 'INTEGER', 'bigint': 'BIGINT', 'decimal': 'NUMERIC(18,4)', 'date': 'DATE', 'datetime': 'TIMESTAMP', 'bool': 'BOOLEAN', 'text': 'VARCHAR(255)'},
            'sqlserver': {'int': 'INT', 'bigint': 'BIGINT', 'decimal': 'DECIMAL(18,4)', 'date': 'DATE', 'datetime': 'DATETIME2', 'bool': 'BIT', 'text': 'NVARCHAR(255)'},
            'snowflake': {'int': 'NUMBER(10,0)', 'bigint': 'NUMBER(19,0)', 'decimal': 'NUMBER(18,4)', 'date': 'DATE', 'datetime': 'TIMESTAMP_NTZ', 'bool': 'BOOLEAN', 'text': 'VARCHAR(255)'}}


def identity(dialect):
    return {'sqlite': 'INTEGER PRIMARY KEY', 'postgres': 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
            'sqlserver': 'INT IDENTITY(1,1) PRIMARY KEY', 'snowflake': 'NUMBER(10,0) IDENTITY(1,1) PRIMARY KEY'}[dialect]


def build_sql(dialect, prefix, stg, dims, date_col, measures, keep, kinds, date_rows):
    t = SQL_TYPE[dialect]
    nn = lambda a, b: f'({a} = {b} OR ({a} IS NULL AND {b} IS NULL))'
    ddl, load = [], []
    ddl.append(f'CREATE TABLE {stg} (\n' + ',\n'.join(f'    {snake(c)} {t[kinds[c]]}' for c in kinds) + '\n);')
    for name, cols in dims.items():
        tbl = f'dim_{name}'
        ddl.append(f'CREATE TABLE {tbl} (\n    {name}_key {identity(dialect)},\n' + ',\n'.join(f'    {snake(c)} {t[kinds[c]]}' for c in cols) + '\n);')
        unknown_vals = ', '.join("'Bilinmiyor'" if kinds[c] == 'text' else 'NULL' for c in cols)
        if dialect == 'sqlserver':
            load.append(f'SET IDENTITY_INSERT {tbl} ON;\nINSERT INTO {tbl} ({name}_key, {", ".join(snake(c) for c in cols)}) VALUES (-1, {unknown_vals});\nSET IDENTITY_INSERT {tbl} OFF;')
        else:
            load.append(f'INSERT INTO {tbl} ({name}_key, {", ".join(snake(c) for c in cols)}) VALUES (-1, {unknown_vals});')
        sel = ', '.join(snake(c) for c in cols)
        load.append(f'INSERT INTO {tbl} ({sel})\nSELECT DISTINCT {sel}\nFROM {stg}\nWHERE ' + ' OR '.join(f'{snake(c)} IS NOT NULL' for c in cols) + ';')
    if date_col:
        ddl.append('CREATE TABLE dim_tarih (\n    tarih_key INTEGER PRIMARY KEY,\n    tarih DATE NOT NULL,\n    yil INTEGER,\n    ceyrek INTEGER,\n    ay INTEGER,\n'
                   f'    ay_adi {t["text"]},\n    gun INTEGER,\n    haftanin_gunu {t["text"]},\n    hafta_sonu INTEGER\n);')
        values = [f"({r['tarih_key']}, '{r['tarih']}', {r['yil']}, {r['ceyrek']}, {r['ay']}, '{r['ay_adi']}', {r['gun']}, '{r['haftanin_gunu']}', {r['hafta_sonu']})" for r in date_rows]
        for i in range(0, len(values), 500):
            load.append('INSERT INTO dim_tarih (tarih_key, tarih, yil, ceyrek, ay, ay_adi, gun, haftanin_gunu, hafta_sonu) VALUES\n' + ',\n'.join(values[i:i + 500]) + ';')
    fct = f'fct_{prefix}'
    fk = [f'    {n}_key INTEGER NOT NULL REFERENCES dim_{n} ({n}_key)' for n in dims]
    if date_col:
        fk.append('    tarih_key INTEGER REFERENCES dim_tarih (tarih_key)')
    ddl.append(f'CREATE TABLE {fct} (\n' + ',\n'.join(fk + [f'    {snake(c)} {t[kinds[c]]}' for c in keep + measures]) + '\n);')
    date_key = {'sqlite': "CAST(strftime('%Y%m%d', s.{c}) AS INTEGER)", 'postgres': "CAST(to_char(s.{c}, 'YYYYMMDD') AS INTEGER)",
                'sqlserver': 'CAST(CONVERT(char(8), s.{c}, 112) AS INT)', 'snowflake': "TO_NUMBER(TO_CHAR(s.{c}, 'YYYYMMDD'))"}[dialect]
    cols = [f'COALESCE(d_{n}.{n}_key, -1)' for n in dims] + ([date_key.format(c=snake(date_col))] if date_col else []) + [f's.{snake(c)}' for c in keep + measures]
    joins = [f'LEFT JOIN dim_{n} d_{n}\n    ON ' + '\n   AND '.join(nn(f'd_{n}.{snake(c)}', f's.{snake(c)}') for c in cs) + f'\n   AND d_{n}.{n}_key <> -1' for n, cs in dims.items()]
    target = [f'{n}_key' for n in dims] + (['tarih_key'] if date_col else []) + [snake(c) for c in keep + measures]
    load.append(f'INSERT INTO {fct} ({", ".join(target)})\nSELECT\n    ' + ',\n    '.join(cols) + f'\nFROM {stg} s\n' + '\n'.join(joins) + ';')
    return '\n\n'.join(ddl) + '\n', '\n\n'.join(load) + '\n'


@op('yildiz-sema', title='Düz dosyadan yıldız şema: boyut, tarih ve olgu tabloları için DDL + yükleme SQL’i (SQLite’ta çalıştırılarak doğrulanır)', domain='warehouse',
    product='Boyutsal model (SQL)', tag='yıldız şema', samples={'satis_detay.csv': 'satis_detay.csv'},
    args=[arg('--dims', default='urun=urun,kategori;bolge=bolge;kanal=kanal', help='Boyutlar: ad=sütun1,sütun2;ad2=sütun3'),
          arg('--date', default='siparis_tarihi', help='Tarih boyutuna bağlanacak sütun (boş bırakılabilir)'), arg('--name', default='satis', help='Olgu tablosu adı (fct_<ad>)'),
          arg('--keep', default='siparis_no', help='Olguda kalacak dejenere boyutlar (sipariş no gibi)'), arg('--drop', default='musteri_eposta', help='Modele alınmayacak sütunlar'),
          arg('--dialect', default='postgres', choices=DIALECTS, help='Çıktı SQL lehçesi (doğrulama her zaman SQLite’ta yapılır)')],
    description='Denormalize bir satış/işlem dosyasını yıldız şemaya çevirir: her boyut için vekil anahtarlı tablo ve “Bilinmiyor” (-1) satırı, tarih boyutu (yıl, çeyrek, ay, gün '
                'adı, hafta sonu), dejenere boyutları ve ölçüleri taşıyan olgu tablosu; boş değerleri güvenli eşleyen yükleme SQL’i. Boyut niteliklerinin anahtara bağımlılığı '
                'veride ölçülür (örneğin aynı ürün iki kategoride görünüyorsa uyarır). Üretilen SQL SQLite’ta çalıştırılır: olgu satır sayısı, ölçü toplamları ve eşleşmeyen '
                'anahtar sayısı kaynakla karşılaştırılır; tutmazsa blok hata verir.',
    input='CSV/XLSX (düz işlem verisi)', output='ddl.sql + yukleme.sql + dogrulama (sonuc.csv) + model.md (Mermaid ER)',
    command='python main.py --input satislar.csv --dims "musteri=musteri_no,sehir;urun=urun_kodu,urun_adi,kategori" --date tarih --keep fatura_no --dialect sqlserver',
    expect={'boyut': 3, 'olgu_satir': 240, 'tarih_gun': 633, 'dogrulama': 'geçti', 'eslesmeyen': 0, 'bagimlilik_ihlali': 0})
def star(columns, rows, args):
    dims = parse_dims(args.dims, columns)
    drop = [c.strip() for c in args.drop.split(',') if c.strip()]
    keep = [c.strip() for c in args.keep.split(',') if c.strip()]
    for c in keep + drop:
        need(c, columns, '--keep/--drop')
    date_col = need(args.date, columns, '--date') if args.date else None
    kinds = {c: infer_column([r[c] for r in rows])[0] for c in columns}
    if date_col and kinds[date_col] != 'date':
        raise ValueError(f'{date_col} saatsiz tarih olarak okunamadı.')
    in_dims = {c for cs in dims.values() for c in cs}
    measures = [c for c in columns if c not in in_dims | set(keep) | set(drop) | {date_col} and kinds[c] in ('int', 'bigint', 'decimal')]
    rest = [c for c in columns if c not in in_dims | set(keep) | set(drop) | {date_col} | set(measures)]
    model_cols = [c for c in columns if c not in drop]
    # functional dependency: within a dimension, the first column should determine the others
    issues = []
    for name, cs in dims.items():
        if len(cs) > 1:
            seen = defaultdict(set)
            for r in rows:
                seen[r[cs[0]].strip()].add(tuple(r[c].strip() for c in cs[1:]))
            bad = {k: v for k, v in seen.items() if len(v) > 1}
            for k, v in list(bad.items())[:5]:
                issues.append(f'dim_{name}: {cs[0]}={k} birden çok niteliğe sahip ({"; ".join(" / ".join(x) for x in sorted(v))}); aynı anahtar iki boyut satırı olur.')
    # date dimension rows
    date_rows = []
    if date_col:
        ds = [p[0].date() for p in (tabular.parse_date(r[date_col]) for r in rows) if p]
        lo, hi = min(ds), max(ds)
        if (hi - lo).days > 366 * 30:
            raise ValueError('Tarih aralığı 30 yılı aşıyor; tarih sütununu kontrol edin.')
        d = lo
        while d <= hi:
            date_rows.append({'tarih_key': int(d.strftime('%Y%m%d')), 'tarih': d.isoformat(), 'yil': d.year, 'ceyrek': (d.month - 1) // 3 + 1, 'ay': d.month,
                              'ay_adi': AY[d.month - 1], 'gun': d.day, 'haftanin_gunu': GUN[d.weekday()], 'hafta_sonu': int(d.weekday() >= 5)})
            d += timedelta(days=1)
    stg = f'stg_{snake(args.name)}'
    stg_kinds = {c: kinds[c] for c in model_cols}
    ddl, load = build_sql(args.dialect, snake(args.name), stg, dims, date_col, measures, keep + rest, stg_kinds, date_rows)
    s_ddl, s_load = (ddl, load) if args.dialect == 'sqlite' else build_sql('sqlite', snake(args.name), stg, dims, date_col, measures, keep + rest, stg_kinds, date_rows)
    # verification: load the parsed file into SQLite staging, run the generated SQL, compare with the source
    nums = {c: numbers(rows, c) for c in model_cols if kinds[c] in ('int', 'bigint', 'decimal')}
    db = sqlite3.connect(':memory:')
    db.executescript(s_ddl)

    def cell(c, i, r):
        v = r[c].strip()
        if not v:
            return None
        if c in nums:
            return nums[c][i]
        if kinds[c] == 'date':
            p = tabular.parse_date(v)
            return p[0].date().isoformat() if p else None
        return v
    db.executemany(f'INSERT INTO {stg} VALUES ({", ".join("?" for _ in model_cols)})', [[cell(c, i, r) for c in model_cols] for i, r in enumerate(rows)])
    db.executescript(s_load)
    fct = f'fct_{snake(args.name)}'
    checks = [('olgu satır sayısı', len(rows), db.execute(f'SELECT COUNT(*) FROM {fct}').fetchone()[0])]
    for m in measures:
        src = round(sum(x for x in nums[m] if x is not None), 4)
        checks.append((f'{m} toplamı', src, round(db.execute(f'SELECT COALESCE(SUM({snake(m)}), 0) FROM {fct}').fetchone()[0], 4)))
    unmatched = 0
    for n, cs in dims.items():
        expected_unknown = sum(all(not r[c].strip() for c in cs) for r in rows)
        got = db.execute(f'SELECT COUNT(*) FROM {fct} WHERE {n}_key = -1').fetchone()[0]
        unmatched += got - expected_unknown
        checks.append((f'dim_{n}: “bilinmiyor”a düşen satır', expected_unknown, got))
        distinct = len({tuple(r[c].strip() for c in cs) for r in rows if any(r[c].strip() for c in cs)})
        checks.append((f'dim_{n}: satır (bilinmiyor hariç)', distinct, db.execute(f'SELECT COUNT(*) FROM dim_{n} WHERE {n}_key <> -1').fetchone()[0]))
    if date_col:
        missing = db.execute(f'SELECT COUNT(*) FROM {fct} f LEFT JOIN dim_tarih d ON d.tarih_key = f.tarih_key WHERE f.tarih_key IS NOT NULL AND d.tarih_key IS NULL').fetchone()[0]
        checks.append(('tarih boyutunda bulunmayan tarih anahtarı', 0, missing))
        unmatched += missing
    db.close()
    out = [{'kontrol': k, 'kaynak': a, 'yildiz_sema': b, 'sonuc': 'tamam' if a == b else 'FARK'} for k, a, b in checks]
    ok = all(o['sonuc'] == 'tamam' for o in out)
    if not ok:
        raise ValueError('Üretilen SQL doğrulamadan geçmedi: ' + '; '.join(f"{o['kontrol']} {o['kaynak']} ≠ {o['yildiz_sema']}" for o in out if o['sonuc'] != 'tamam'))
    er = ['```mermaid', 'erDiagram'] + [f'    dim_{n} ||--o{{ {fct} : "{n}_key"' for n in dims] + ([f'    dim_tarih ||--o{{ {fct} : tarih_key'] if date_col else []) + ['```']
    md = [f'# Yıldız şema: {fct}', '', f'Olgu tanecikliği: kaynak dosyanın her satırı ({len(rows)} satır). Ölçüler: {", ".join(measures) or "yok"}. '
          f'Dejenere boyut: {", ".join(keep + rest) or "yok"}. Modele alınmayan: {", ".join(drop) or "yok"}.', ''] + er
    return Result(f'{len(dims)} boyut{" + tarih" if date_col else ""} ve {fct}; SQLite’ta doğrulandı ({len(rows)} satır, {len(measures)} ölçü toplamı tuttu)',
                  ['kontrol', 'kaynak', 'yildiz_sema', 'sonuc'], out,
                  {'boyut': len(dims), 'olgu_satir': len(rows), 'tarih_gun': len(date_rows), 'dogrulama': 'geçti', 'eslesmeyen': unmatched, 'bagimlilik_ihlali': len(issues)},
                  files={'ddl.sql': ddl, 'yukleme.sql': load, 'model.md': '\n'.join(md)},
                  notes=[f'Önce {stg} tablosuna dosyayı yükleyin (COPY / BULK INSERT / COPY INTO), sonra yukleme.sql’i sırayla çalıştırın. Doğrulama SQLite’ta yapıldı; '
                         f'seçilen lehçe ({args.dialect}) yalnızca tip ve anahtar sözdiziminde farklıdır.'] + issues)
